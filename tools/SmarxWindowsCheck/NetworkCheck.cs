using System.Text;
using SMARX.Models;
using SMARX.Services.Windows;

/// <summary>
/// Mode réseau : le script s'exécute sur un poste client du domaine, sous un administrateur du domaine (tâche planifiée
/// dans sa session, pour avoir son ticket Kerberos). Par PowerShell à distance, il recrée sur le serveur le serveur
/// d'exemple, ses comptes (smx-*, mots de passe tirés au hasard, gardés en mémoire) et ses partages (smx-*). Puis, depuis
/// le poste, il ouvre chaque objet de chaque partage avec chacun des 14 droits spéciaux sous l'identité réseau de chaque
/// compte (LogonUser, LOGON32_LOGON_NEW_CREDENTIALS), et liste chaque dossier par le partage (énumération basée sur
/// l'accès). Tout est supprimé à la fin. Sortie : C:\Windows\Temp\smarx-net.txt (Fidelity/windows-shares.txt).
/// </summary>
internal static class NetworkCheck
{
    private const string Prefix = "smx-";
    private const string RealRoot = @"C:\SmarxCheck";

    private static readonly Dictionary<string, string> WellKnownSids = new()
    {
        [WellKnown.Administrators] = "S-1-5-32-544", [WellKnown.Users] = "S-1-5-32-545", [WellKnown.System] = "S-1-5-18",
        [WellKnown.AuthenticatedUsers] = "S-1-5-11", [WellKnown.CreatorOwner] = "S-1-3-0", [WellKnown.Everyone] = "S-1-1-0",
        [WellKnown.OwnerRights] = "S-1-3-4", [WellKnown.Interactive] = "S-1-5-4", [WellKnown.Network] = "S-1-5-2"
    };

    public static string Script(WindowsHost host, string server)
    {
        var s = new StringBuilder();
        void L(string line = "") => s.Append(line).Append('\n');
        static string Q(string text) => "'" + text.Replace("'", "''") + "'";
        string Real(string enginePath)
        {
            var rest = enginePath[(host.Root.Name.Length + 1)..];
            return rest.Length == 0 ? RealRoot : RealRoot + "\\" + rest;
        }
        static int AceFlags(AceInheritance i) =>
            (i.HasFlag(AceInheritance.ObjectInherit) ? 1 : 0) | (i.HasFlag(AceInheritance.ContainerInherit) ? 2 : 0)
            | (i.HasFlag(AceInheritance.NoPropagate) ? 4 : 0) | (i.HasFlag(AceInheritance.InheritOnly) ? 8 : 0);
        string Account(string name) => WellKnownSids.TryGetValue(name, out var sid) ? "*" + sid
            : name == "Administrator" ? "$netbios\\Administrator" : $"$netbios\\{Prefix}{name}";

        var nodes = Walk(host.Root, host.Root.Name + "\\").ToList();
        var testUsers = host.Users.Where(u => !u.IsBuiltInAdministrator).ToList();
        var testGroups = host.Groups.Where(g => !WellKnownSids.ContainsKey(g.Name)).ToList();

        L("# SMAR-X network check, generated by tools/SmarxWindowsCheck --network. Run on a domain client, as a domain admin, in their session.");
        L("$ErrorActionPreference = 'Stop'");
        L($"$Server = {Q(server)}");
        L("$Out = 'C:\\Windows\\Temp\\smarx-net.txt'");
        L("Remove-Item -LiteralPath $Out -ErrorAction SilentlyContinue");
        L("function Write-Result([string]$line) { Add-Content -LiteralPath $Out -Value $line -Encoding UTF8 }");
        L("function New-Password { $b = New-Object byte[] 24; [Security.Cryptography.RandomNumberGenerator]::Create().GetBytes($b); [Convert]::ToBase64String($b) + 'aA1!' }");
        L("$passwords = @{}");
        foreach (var u in testUsers)
            L($"$passwords[{Q(u.Name)}] = New-Password");
        L();

        // ── Sur le serveur : comptes, arborescence, DACL, partages ; et le ménage ──
        L("$cleanup = {");
        L("    $domain = Get-ADDomain");
        L($"    Get-SmbShare -Name '{Prefix}*' -ErrorAction SilentlyContinue | Remove-SmbShare -Force");
        L($"    if (Test-Path -LiteralPath {Q(RealRoot)}) {{ & icacls.exe {Q(RealRoot)} /reset /T /C /Q | Out-Null; & cmd.exe /c rd /s /q {Q(RealRoot)} }}");
        L("    if (Get-ADOrganizationalUnit -Filter \"Name -eq 'SMARX-Test'\" -SearchBase $domain.DistinguishedName -SearchScope OneLevel) {");
        L("        $ou = \"OU=SMARX-Test,$($domain.DistinguishedName)\"");
        L("        Set-ADOrganizationalUnit -Identity $ou -ProtectedFromAccidentalDeletion $false");
        L("        Remove-ADOrganizationalUnit -Identity $ou -Recursive -Confirm:$false");
        L("    }");
        L("}");
        L("$setup = {");
        L("    param($passwords, $cleanup)");
        L("    $ErrorActionPreference = 'Stop'");
        L("    & ([scriptblock]::Create($cleanup))");
        L("    $domain = Get-ADDomain");
        L("    $netbios = $domain.NetBIOSName");
        L("    $ou = \"OU=SMARX-Test,$($domain.DistinguishedName)\"");
        L("    function Invoke-Icacls { $o = & icacls.exe @args /Q 2>&1; if ($LASTEXITCODE -ne 0 -or ($o -match 'Failed processing [1-9]')) { throw \"icacls $($args -join ' ') failed: $o\" } }");
        L("    Add-Type -TypeDefinition @'");
        L("""
using System;
using System.ComponentModel;
using System.Runtime.InteropServices;
using System.Security.AccessControl;
using System.Security.Principal;

public static class SmarxDacl
{
    [DllImport("advapi32.dll", CharSet = CharSet.Unicode)] static extern uint SetNamedSecurityInfo(string name, int type, uint information, IntPtr owner, IntPtr group, byte[] dacl, IntPtr sacl);

    // Écrit les ACE explicites « Allow|SID|drapeaux|masque » dans l'ordre donné, la DACL protégée ou non
    public static void SetDacl(string path, bool isProtected, string[] aces)
    {
        RawAcl acl = new RawAcl(GenericAcl.AclRevision, aces.Length);
        for (int i = 0; i < aces.Length; i++)
        {
            string[] f = aces[i].Split('|');
            acl.InsertAce(i, new CommonAce((AceFlags)int.Parse(f[2]), f[0] == "Deny" ? AceQualifier.AccessDenied : AceQualifier.AccessAllowed,
                unchecked((int)Convert.ToUInt32(f[3], 16)), new SecurityIdentifier(f[1]), false, null));
        }
        byte[] binary = new byte[acl.BinaryLength];
        acl.GetBinaryForm(binary, 0);
        uint error = SetNamedSecurityInfo(path, 1, 4u | (isProtected ? 0x80000000u : 0x20000000u), IntPtr.Zero, IntPtr.Zero, binary, IntPtr.Zero);
        if (error != 0) throw new Win32Exception((int)error);
    }
}
""");
        L("'@");
        L("    New-ADOrganizationalUnit -Name 'SMARX-Test' -Path $domain.DistinguishedName -ProtectedFromAccidentalDeletion $false");
        foreach (var g in testGroups)
            L($"    New-ADGroup -Name {Q(Prefix + g.Name)} -SamAccountName {Q(Prefix + g.Name)} -GroupScope DomainLocal -GroupCategory Security -Path $ou");
        foreach (var u in testUsers)
            L($"    New-ADUser -Name {Q(Prefix + u.Name)} -SamAccountName {Q(Prefix + u.Name)} -UserPrincipalName \"{Prefix}{u.Name}@$($domain.DNSRoot)\" -AccountPassword (ConvertTo-SecureString $passwords[{Q(u.Name)}] -AsPlainText -Force) -Enabled $true -Path $ou");
        foreach (var u in testUsers)
            foreach (var g in u.Groups)
                L(g == WellKnown.Administrators
                    ? $"    Add-ADGroupMember -Identity (Get-ADGroup -Filter \"SID -eq 'S-1-5-32-544'\") -Members {Q(Prefix + u.Name)}"
                    : $"    Add-ADGroupMember -Identity {Q(Prefix + g)} -Members {Q(Prefix + u.Name)}");
        L("    $sids = @{}");
        foreach (var (name, sid) in WellKnownSids)
            L($"    $sids[{Q(name)}] = {Q(sid)}");
        foreach (var u in testUsers)
            L($"    $sids[{Q(u.Name)}] = (Get-ADUser {Q(Prefix + u.Name)}).SID.Value");
        foreach (var g in testGroups)
            L($"    $sids[{Q(g.Name)}] = (Get-ADGroup {Q(Prefix + g.Name)}).SID.Value");
        L("    $sids['Administrator'] = \"$($domain.DomainSID)-500\"");
        L("    function Set-Dacl([string]$path, [bool]$protected, [string[]]$aces) {");
        L("        [SmarxDacl]::SetDacl($path, $protected, [string[]]@($aces | ForEach-Object { $f = $_.Split('|'); \"$($f[0])|$($sids[$f[1]])|$($f[2])|$($f[3])\" }))");
        L("    }");
        L("    function Account-Name([string]$name) { ([Security.Principal.SecurityIdentifier]$sids[$name]).Translate([Security.Principal.NTAccount]).Value }");
        L($"    New-Item -ItemType Directory -Path {Q(RealRoot)} | Out-Null");
        foreach (var (node, path) in nodes.Skip(1))
            L($"    New-Item -ItemType {(node.IsDirectory ? "Directory" : "File")} -Path {Q(Real(path))} | Out-Null");
        foreach (var (node, path) in nodes)
            L($"    Invoke-Icacls {Q(Real(path))} /setowner \"{Account(node.Owner)}\"");
        foreach (var (node, path) in nodes)
        {
            var aces = NtfsInheritance.Explicit(node).Select(a => Q($"{a.Type}|{a.Trustee}|{AceFlags(a.Inheritance)}|{(uint)a.Mask:X8}"));
            L($"    Set-Dacl {Q(Real(path))} ${(!node.InheritanceEnabled || node == host.Root).ToString().ToLowerInvariant()} @({string.Join(", ", aces)})");
        }
        // Les partages : leurs autorisations exactes (sans paramètre d'accès, Windows donnerait Lecture à Tout le monde)
        foreach (var share in host.Shares)
        {
            string Accounts(ShareRight right) => string.Join(", ", share.Permissions.Where(a => a.Type == AceType.Allow && a.Right == right).Select(a => $"(Account-Name {Q(a.Trustee)})"));
            var access = new[] { (ShareRight.FullControl, "-FullAccess"), (ShareRight.Change, "-ChangeAccess"), (ShareRight.Read, "-ReadAccess") }
                .Where(x => share.Permissions.Any(a => a.Type == AceType.Allow && a.Right == x.Item1))
                .Select(x => $"{x.Item2} @({Accounts(x.Item1)})");
            L($"    New-SmbShare -Name {Q(Prefix + share.Name)} -Path {Q(Real(share.Path))} -FolderEnumerationMode {(share.AccessBasedEnumeration ? "AccessBased" : "Unrestricted")} {string.Join(" ", access)} | Out-Null");
            foreach (var deny in share.Permissions.Where(a => a.Type == AceType.Deny))
                L($"    Block-SmbShareAccess -Name {Q(Prefix + share.Name)} -AccountName (Account-Name {Q(deny.Trustee)}) -Force | Out-Null");
        }
        L("    \"$($domain.NetBIOSName)|$($domain.DNSRoot)\"");
        L("}");
        L();

        // ── Sur le poste : l'identité réseau de chaque compte, puis chaque ouverture et chaque liste ──
        L("Add-Type -TypeDefinition @'");
        L("""
using System;
using System.Collections.Generic;
using System.ComponentModel;
using System.IO;
using System.Runtime.InteropServices;
using System.Security.Principal;
using Microsoft.Win32.SafeHandles;

public static class NetProbe
{
    [StructLayout(LayoutKind.Sequential)] struct UNICODE_STRING { public ushort Length; public ushort MaximumLength; public IntPtr Buffer; }
    [StructLayout(LayoutKind.Sequential)] struct OBJECT_ATTRIBUTES { public int Length; public IntPtr RootDirectory; public IntPtr ObjectName; public uint Attributes; public IntPtr SecurityDescriptor; public IntPtr SecurityQualityOfService; }
    [StructLayout(LayoutKind.Sequential)] struct IO_STATUS_BLOCK { public IntPtr Status; public IntPtr Information; }
    [DllImport("ntdll.dll")] static extern int NtOpenFile(out IntPtr handle, uint access, ref OBJECT_ATTRIBUTES attributes, out IO_STATUS_BLOCK status, uint share, uint options);
    [DllImport("ntdll.dll")] static extern int NtClose(IntPtr handle);
    [DllImport("advapi32.dll", SetLastError = true, CharSet = CharSet.Unicode)] static extern bool LogonUser(string user, string domain, string password, int type, int provider, out IntPtr token);
    [DllImport("ntdll.dll")] static extern int NtQueryInformationFile(IntPtr handle, out IO_STATUS_BLOCK status, byte[] info, int length, int infoClass);
    [DllImport("ntdll.dll")] static extern int NtSetInformationFile(IntPtr handle, out IO_STATUS_BLOCK status, byte[] info, int length, int infoClass);

    // Le client SMB accepte une ouverture qui ne demande que des attributs, Synchroniser ou Parcours sans consulter le
    // serveur : on fait alors une vraie opération, qui oblige le serveur à décider (écrire les attributs sans rien
    // changer, les lire, ou lire les informations standard)
    static int Settle(IntPtr handle, uint access)
    {
        IO_STATUS_BLOCK io;
        if (access == 0x100) return NtSetInformationFile(handle, out io, new byte[40], 40, 4);
        if (access == 0x80) return NtQueryInformationFile(handle, out io, new byte[40], 40, 4);
        if (access == 0x100000 || access == 0x20) return NtQueryInformationFile(handle, out io, new byte[24], 24, 5);
        return 0;
    }

    static int Open(string path, uint access)
    {
        IntPtr buffer = Marshal.StringToHGlobalUni(path);
        IntPtr namePtr = Marshal.AllocHGlobal(Marshal.SizeOf(typeof(UNICODE_STRING)));
        try
        {
            UNICODE_STRING name = new UNICODE_STRING { Length = (ushort)(path.Length * 2), MaximumLength = (ushort)(path.Length * 2 + 2), Buffer = buffer };
            Marshal.StructureToPtr(name, namePtr, false);
            OBJECT_ATTRIBUTES attributes = new OBJECT_ATTRIBUTES { Length = Marshal.SizeOf(typeof(OBJECT_ATTRIBUTES)), ObjectName = namePtr, Attributes = 0x40 };
            IntPtr handle;
            IO_STATUS_BLOCK io;
            int status = NtOpenFile(out handle, access, ref attributes, out io, 7, 0);
            if (status == 0)
            {
                status = Settle(handle, access);
                NtClose(handle);
            }
            return status;
        }
        finally
        {
            Marshal.FreeHGlobal(namePtr);
            Marshal.FreeHGlobal(buffer);
        }
    }

    // « A|objet|droit|statut » par ouverture, « L|dossier|noms séparés par / » (ou « !erreur ») par liste
    static string[] Probe(string[] opens, uint[] rights, string[] folders)
    {
        List<string> lines = new List<string>();
        for (int p = 0; p < opens.Length; p++)
            for (int r = 0; r < rights.Length; r++)
                lines.Add("A|" + p + "|" + r + "|" + Open(opens[p], rights[r]).ToString("X8"));
        for (int f = 0; f < folders.Length; f++)
        {
            string names;
            try
            {
                List<string> found = new List<string>();
                foreach (string entry in Directory.GetFileSystemEntries(folders[f])) found.Add(Path.GetFileName(entry));
                found.Sort(StringComparer.OrdinalIgnoreCase);
                names = string.Join("/", found.ToArray());
            }
            catch (UnauthorizedAccessException) { names = "!denied"; }
            catch (Exception e) { names = "!" + e.GetType().Name; }
            lines.Add("L|" + f + "|" + names);
        }
        return lines.ToArray();
    }

    // Sous l'identité réseau du compte (le jeton local reste celui de l'appelant) ; sans compte, sous l'appelant
    public static string[] Run(string domain, string user, string password, string[] opens, uint[] rights, string[] folders)
    {
        if (user == null || user.Length == 0) return Probe(opens, rights, folders);
        IntPtr token;
        if (!LogonUser(user, domain, password, 9, 3, out token)) throw new Win32Exception();
        string[] result = null;
        using (SafeAccessTokenHandle handle = new SafeAccessTokenHandle(token))
            WindowsIdentity.RunImpersonated(handle, () => { result = Probe(opens, rights, folders); });
        return result;
    }
}
""");
        L("'@");
        L();

        // Les objets de chaque partage, par leur chemin réseau, et les dossiers à lister
        var opens = new List<(string Share, string Path, string Tail)>();
        var folders = new List<(string Share, string Path, string Tail)>();
        foreach (var share in host.Shares)
            foreach (var (node, path) in nodes.Where(n => share.Contains(n.Path)))
            {
                var rest = share.Unc(host.Name, path)[$@"\\{host.Name}\{share.Name}".Length..];
                opens.Add((share.Name, path, rest));
                if (node.IsDirectory) folders.Add((share.Name, path, rest));
            }

        L("try {");
        L("    $info = (Invoke-Command -ComputerName $Server -ScriptBlock $setup -ArgumentList $passwords, $cleanup.ToString()) | Select-Object -Last 1");
        L("    $netbios, $dnsRoot = $info.Split('|')");
        L("    Write-Result \"# $((Get-CimInstance Win32_OperatingSystem).Caption) $([Environment]::OSVersion.Version) -> \\\\$Server, domain $dnsRoot\"");
        L("    $shares = @(" + string.Join(", ", opens.Select(o => Q(o.Share))) + ")");
        L("    $engine = @(" + string.Join(", ", opens.Select(o => Q(o.Path))) + ")");
        L("    $opens = @(" + string.Join(", ", opens.Select(o => $"('\\??\\UNC\\' + $Server + {Q($"\\{Prefix}{o.Share}{o.Tail}")})")) + ")");
        L("    $folderShares = @(" + string.Join(", ", folders.Select(o => Q(o.Share))) + ")");
        L("    $folderEngine = @(" + string.Join(", ", folders.Select(o => Q(o.Path))) + ")");
        L("    $folders = @(" + string.Join(", ", folders.Select(o => $"('\\\\' + $Server + {Q($"\\{Prefix}{o.Share}{o.Tail}")})")) + ")");
        L("    $codes = @(" + string.Join(", ", Ntfs.Special.Select(x => Q(x.Code))) + ")");
        L("    $rights = [uint32[]]@(" + string.Join(", ", Ntfs.Special.Select(x => $"0x{(int)x.Right:X}")) + ")");
        L("    $accounts = @(@{ Name = 'Administrator'; User = '' }" + string.Concat(testUsers.Select(u => $", @{{ Name = {Q(u.Name)}; User = {Q(Prefix + u.Name)} }}")) + ")");
        // Le client SMB garde en cache, une dizaine de secondes, les attributs lus par un compte et les sert aux suivants :
        // on laisse ce cache expirer entre deux comptes
        L("    foreach ($a in $accounts) {");
        L("        if ($a.Name -ne 'Administrator') { Start-Sleep -Seconds 15 }");
        L("        $password = if ($a.User) { $passwords[$a.Name] } else { '' }");
        L("        foreach ($line in [NetProbe]::Run($netbios, $a.User, $password, $opens, $rights, $folders)) {");
        L("            $f = $line.Split('|')");
        L("            if ($f[0] -eq 'A') {");
        L("                $result = switch ($f[3]) { '00000000' { 'yes' } 'C0000022' { 'no' } default { 'err-' + $f[3] } }");
        L("                Write-Result \"NACCESS|$($a.Name)|$($shares[[int]$f[1]])|$($engine[[int]$f[1]])|$($codes[[int]$f[2]])|$result\"");
        L("            } else {");
        L("                Write-Result \"NLIST|$($a.Name)|$($folderShares[[int]$f[1]])|$($folderEngine[[int]$f[1]])|$($f[2])\"");
        L("            }");
        L("        }");
        L("    }");
        L("    Write-Result '# done'");
        L("}");
        L("catch { Write-Result \"ERROR|$($_.Exception.Message) at $($_.InvocationInfo.ScriptLineNumber)\" }");
        L("finally {");
        L("    try { Invoke-Command -ComputerName $Server -ScriptBlock $cleanup } catch { Write-Result \"CLEANUP|$($_.Exception.Message)\" }");
        L("    $passwords.Clear()");
        L("}");
        return s.ToString();
    }

    private static IEnumerable<(NtfsNode Node, string Path)> Walk(NtfsNode node, string path)
    {
        yield return (node, path);
        foreach (var child in node.Children)
            foreach (var item in Walk(child, WindowsHost.Combine(path, child.Name)))
                yield return item;
    }
}
