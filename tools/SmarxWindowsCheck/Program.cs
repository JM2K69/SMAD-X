// Identités prédéfinies : par SID, pour ne dépendre ni de la langue du serveur ni de son nom
var wellKnownSids = new Dictionary<string, string>
{
    [WellKnown.Administrators] = "S-1-5-32-544", [WellKnown.Users] = "S-1-5-32-545", [WellKnown.System] = "S-1-5-18",
    [WellKnown.AuthenticatedUsers] = "S-1-5-11", [WellKnown.CreatorOwner] = "S-1-3-0", [WellKnown.Everyone] = "S-1-1-0",
    [WellKnown.OwnerRights] = "S-1-3-4", [WellKnown.Interactive] = "S-1-5-4", [WellKnown.Network] = "S-1-5-2"
};
var testUsers = host.Users.Where(u => !u.IsBuiltInAdministrator).ToList();
var testGroups = host.Groups.Where(g => !wellKnownSids.ContainsKey(g.Name)).ToList();
string Account(string name) => wellKnownSids.TryGetValue(name, out var sid) ? "*" + sid
    : name == "Administrator" ? "$netbios\\Administrator" : $"$netbios\\{Prefix}{name}";

static IEnumerable<(NtfsNode Node, string Path)> Walk(NtfsNode node, string path)
{
    yield return (node, path);
    foreach (var child in node.Children)
        foreach (var item in Walk(child, WindowsHost.Combine(path, child.Name)))
            yield return item;
}
var nodes = Walk(host.Root, host.Root.Name + "\\").ToList();
// « D:\ » de l'exemple devient C:\SmarxCheck, « D:\Partages » C:\SmarxCheck\Partages
string Real(string enginePath)
{
    var rest = enginePath[(host.Root.Name.Length + 1)..];
    return rest.Length == 0 ? RealRoot : RealRoot + "\\" + rest;
}
string Q(string text) => "'" + text.Replace("'", "''") + "'";
// Drapeaux d'une ACE Windows : OI 1, CI 2, NP 4, IO 8
static int AceFlags(AceInheritance i) =>
    (i.HasFlag(AceInheritance.ObjectInherit) ? 1 : 0) | (i.HasFlag(AceInheritance.ContainerInherit) ? 2 : 0)
    | (i.HasFlag(AceInheritance.NoPropagate) ? 4 : 0) | (i.HasFlag(AceInheritance.InheritOnly) ? 8 : 0);

var s = new StringBuilder();
void L(string line = "") => s.Append(line).Append('\n');

L("# SMAR-X Windows check, generated by tools/SmarxWindowsCheck. Run as SYSTEM on a domain controller.");
L("$ErrorActionPreference = 'Stop'");
