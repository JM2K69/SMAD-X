L("$ou = \"OU=SMARX-Test,$($domain.DistinguishedName)\"");
L("function Write-Result([string]$line) { Add-Content -LiteralPath $Out -Value $line -Encoding UTF8 }");
L("function Invoke-Icacls { $o = & icacls.exe @args /Q 2>&1; if ($LASTEXITCODE -ne 0 -or ($o -match 'Failed processing [1-9]')) { throw \"icacls $($args -join ' ') failed: $o\" } }");
L("function Remove-Test {");
L("    if (Test-Path -LiteralPath $Root) { & cmd.exe /c rd /s /q $Root }");
L("    if (Get-ADOrganizationalUnit -Filter \"Name -eq 'SMARX-Test'\" -SearchBase $domain.DistinguishedName -SearchScope OneLevel) {");
