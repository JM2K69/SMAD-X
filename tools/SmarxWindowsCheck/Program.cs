// Arborescence : les objets, puis leurs propriétaires, puis de haut en bas la DACL de chacun, ses ACE explicites écrites
// telles quelles, dans l'ordre du moteur (icacls, lui, range à sa façon celles qu'il ajoute) : Windows y ajoute les ACE
// héritées et propage aux enfants, CREATOR OWNER devenant le propriétaire de chacun.
L("    New-Item -ItemType Directory -Path $Root | Out-Null");
foreach (var (node, path) in nodes.Skip(1))
    L($"    New-Item -ItemType {(node.IsDirectory ? "Directory" : "File")} -Path {Q(Real(path))} | Out-Null");
foreach (var (node, path) in nodes)
    L($"    Invoke-Icacls {Q(Real(path))} /setowner \"{Account(node.Owner)}\"");
foreach (var (node, path) in nodes)
{
    var aces = NtfsInheritance.Explicit(node).Select(a => Q($"{a.Type}|{a.Trustee}|{AceFlags(a.Inheritance)}|{(uint)a.Mask:X8}"));
    L($"    Set-Dacl {Q(Real(path))} ${(!node.InheritanceEnabled || node == host.Root).ToString().ToLowerInvariant()} @({string.Join(", ", aces)})");
}
L();

L("    function Engine-Sid([string]$sid) { if ($names.ContainsKey($sid)) { $names[$sid] } else { \"?$sid\" } }");
L("    function Engine-Name($identity) { Engine-Sid $identity.Translate([Security.Principal.SecurityIdentifier]).Value }");
L();

// ACL réelles : propriétaire, et chaque ACE dans l'ordre de la DACL avec ses drapeaux (OI 1, CI 2, NP 4, IO 8, héritée 0x10)
L("    $engine = @(" + string.Join(", ", nodes.Select(n => Q(n.Path))) + ")");
L("    $real = @(" + string.Join(", ", nodes.Select(n => Q(Real(n.Path)))) + ")");
L("    for ($n = 0; $n -lt $real.Count; $n++) {");
L("        $acl = Get-Acl -LiteralPath $real[$n]");
L("        Write-Result \"OWNER|$($engine[$n])|$(Engine-Name ([Security.Principal.NTAccount]$acl.Owner))\"");
L("        $i = 0");
L("        foreach ($ace in [SmarxProbe]::Dacl($real[$n])) {");
L("            $i++");
L("            $f = $ace.Split('|')");
L("            Write-Result \"ACL|$($engine[$n])|$i|$($f[0])|$(Engine-Sid $f[1])|$($f[2])|$($f[3])\"");
L("        }");
L("    }");
L();

// Accès : chaque compte, chaque objet, chaque droit spécial. Les tickets S4U d'un passage précédent, encore en cache pour
// la session SYSTEM, porteraient les SID des comptes de test supprimés depuis : on les purge.
L("    & klist.exe -li 0x3e7 purge | Out-Null");
L("    $nt = $real | ForEach-Object { '\\??\\' + $_ }");
L("    $codes = @(" + string.Join(", ", Ntfs.Special.Select(x => Q(x.Code))) + ")");
L("    $rights = [uint32[]]@(" + string.Join(", ", Ntfs.Special.Select(x => $"0x{(int)x.Right:X}")) + ")");
L("    $probes = @(");
var probes = new List<string> { $"@{{ Name = 'Administrator'; Upn = \"Administrator@$($domain.DNSRoot)\"; Restricted = $false; TakeOwnership = $true; Elevated = 'False' }}" };
foreach (var u in testUsers)
{
    var upn = $"\"{Prefix}{u.Name}@$($domain.DNSRoot)\"";
    if (WindowsGroups.IsAdministrator(host, u))
    {
        probes.Add($"@{{ Name = {Q(u.Name)}; Upn = {upn}; Restricted = $true; TakeOwnership = $false; Elevated = 'False' }}");
        probes.Add($"@{{ Name = {Q(u.Name)}; Upn = {upn}; Restricted = $false; TakeOwnership = $true; Elevated = 'True' }}");
    }
    else
        probes.Add($"@{{ Name = {Q(u.Name)}; Upn = {upn}; Restricted = $false; TakeOwnership = $false; Elevated = 'False' }}");
}
L("        " + string.Join(",\n        ", probes));
L("    )");
L("    foreach ($p in $probes) {");
L("        foreach ($line in [SmarxProbe]::Run($p.Upn, $p.Restricted, $p.TakeOwnership, $nt, $rights)) {");
L("            $f = $line.Split('|')");
L("            $result = switch ($f[2]) { '00000000' { 'yes' } 'C0000022' { 'no' } default { 'err-' + $f[2] } }");
L("            Write-Result \"ACCESS|$($p.Name)|$($p.Elevated)|$($engine[[int]$f[0]])|$($codes[[int]$f[1]])|$result\"");
L("        }");
L("    }");
L("    Write-Result '# done'");
L("}");
L("catch { Write-Result \"ERROR|$($_.Exception.Message) at $($_.InvocationInfo.ScriptLineNumber)\" }");
L("finally { Remove-Test }");

