// Sonde : ouverture avec un droit exact, sous un jeton S4U (SYSTEM a SeTcbPrivilege : jeton d'emprunt d'identité utilisable)
L("Add-Type -TypeDefinition @'");
L("""
using System;
using System.Collections.Generic;
using System.ComponentModel;
using System.Runtime.InteropServices;
using System.Security.AccessControl;
using System.Security.Principal;

public static class SmarxProbe
{
    [StructLayout(LayoutKind.Sequential)] struct UNICODE_STRING { public ushort Length; public ushort MaximumLength; public IntPtr Buffer; }
    [StructLayout(LayoutKind.Sequential)] struct OBJECT_ATTRIBUTES { public int Length; public IntPtr RootDirectory; public IntPtr ObjectName; public uint Attributes; public IntPtr SecurityDescriptor; public IntPtr SecurityQualityOfService; }
    [StructLayout(LayoutKind.Sequential)] struct IO_STATUS_BLOCK { public IntPtr Status; public IntPtr Information; }
    [StructLayout(LayoutKind.Sequential)] struct LUID { public uint Low; public int High; }
    [StructLayout(LayoutKind.Sequential)] struct TOKEN_PRIVILEGES { public int Count; public LUID Luid; public int Attributes; }
    [StructLayout(LayoutKind.Sequential)] struct SID_AND_ATTRIBUTES { public IntPtr Sid; public int Attributes; }

    [DllImport("ntdll.dll")] static extern int NtOpenFile(out IntPtr handle, uint access, ref OBJECT_ATTRIBUTES attributes, out IO_STATUS_BLOCK status, uint share, uint options);
    [DllImport("ntdll.dll")] static extern int NtClose(IntPtr handle);
    [DllImport("advapi32.dll", SetLastError = true)] static extern bool DuplicateTokenEx(IntPtr existing, uint access, IntPtr attributes, int level, int type, out IntPtr token);
    [DllImport("advapi32.dll", SetLastError = true, CharSet = CharSet.Unicode)] static extern bool LookupPrivilegeValue(string system, string name, out LUID luid);
    [DllImport("advapi32.dll", SetLastError = true)] static extern bool AdjustTokenPrivileges(IntPtr token, bool disableAll, ref TOKEN_PRIVILEGES state, int length, IntPtr previous, IntPtr returnLength);
    [DllImport("advapi32.dll", SetLastError = true)] static extern bool CreateRestrictedToken(IntPtr existing, uint flags, uint disableCount, SID_AND_ATTRIBUTES[] disable, uint deleteCount, IntPtr delete, uint restrictCount, IntPtr restrict, out IntPtr token);
    [DllImport("kernel32.dll")] static extern bool CloseHandle(IntPtr handle);
    [DllImport("advapi32.dll", SetLastError = true, CharSet = CharSet.Unicode)] static extern bool GetFileSecurity(string file, uint information, byte[] descriptor, uint length, out uint needed);
    [DllImport("advapi32.dll", CharSet = CharSet.Unicode)] static extern uint SetNamedSecurityInfo(string name, int type, uint information, IntPtr owner, IntPtr group, byte[] dacl, IntPtr sacl);

    // Écrit les ACE explicites « Allow|SID|drapeaux|masque » dans l'ordre donné, la DACL protégée ou non : Windows y
    // ajoute les ACE héritées du parent et propage aux enfants
    public static void SetDacl(string path, bool isProtected, string[] aces)
    {
        RawAcl acl = new RawAcl(GenericAcl.AclRevision, aces.Length);
        for (int i = 0; i < aces.Length; i++)
        {
            string[] f = aces[i].Split('|');
            acl.InsertAce(i, new CommonAce((AceFlags)int.Parse(f[2]), f[0] == "Deny" ? AceQualifier.AccessDenied : AceQualifier.AccessAllowed,
                unchecked((int)Convert.ToUInt32(f[3], 16)), new SecurityIdentifier(f[1]), false, null));
        }
        byte[] binary = new byte[acl.BinaryLength];
        acl.GetBinaryForm(binary, 0);
        uint error = SetNamedSecurityInfo(path, 1, 4u | (isProtected ? 0x80000000u : 0x20000000u), IntPtr.Zero, IntPtr.Zero, binary, IntPtr.Zero);
        if (error != 0) throw new Win32Exception((int)error);
    }

    // La DACL telle qu'elle est stockée, dans son ordre : « Allow|SID|drapeaux d'ACE|masque » par ACE
    public static string[] Dacl(string path)
    {
        uint needed;
        GetFileSecurity(path, 4, null, 0, out needed);
        byte[] buffer = new byte[needed];
        if (!GetFileSecurity(path, 4, buffer, needed, out needed)) throw new Win32Exception();
        List<string> lines = new List<string>();
        foreach (GenericAce ace in new RawSecurityDescriptor(buffer, 0).DiscretionaryAcl)
        {
            CommonAce common = (CommonAce)ace;
            lines.Add((common.AceQualifier == AceQualifier.AccessDenied ? "Deny" : "Allow") + "|" + common.SecurityIdentifier.Value + "|" + (int)common.AceFlags + "|" + common.AccessMask.ToString("X8"));
        }
        return lines.ToArray();
    }

    static int Open(string path, uint access)
    {
        IntPtr buffer = Marshal.StringToHGlobalUni(path);
        IntPtr namePtr = Marshal.AllocHGlobal(Marshal.SizeOf(typeof(UNICODE_STRING)));
        try
        {
            UNICODE_STRING name = new UNICODE_STRING { Length = (ushort)(path.Length * 2), MaximumLength = (ushort)(path.Length * 2 + 2), Buffer = buffer };
            Marshal.StructureToPtr(name, namePtr, false);
            OBJECT_ATTRIBUTES attributes = new OBJECT_ATTRIBUTES { Length = Marshal.SizeOf(typeof(OBJECT_ATTRIBUTES)), ObjectName = namePtr, Attributes = 0x40 };
            IntPtr handle;
            IO_STATUS_BLOCK io;
            int status = NtOpenFile(out handle, access, ref attributes, out io, 7, 0);
            if (status == 0) NtClose(handle);
            return status;
        }
        finally
        {
            Marshal.FreeHGlobal(namePtr);
            Marshal.FreeHGlobal(buffer);
        }
    }

    // Une ligne « chemin|droit|statut » par ouverture tentée sous le jeton du compte
    public static string[] Run(string upn, bool restricted, bool takeOwnership, string[] paths, uint[] rights)
    {
        List<string> lines = new List<string>();
        using (WindowsIdentity identity = new WindowsIdentity(upn))
        {
            IntPtr token;
            if (!DuplicateTokenEx(identity.Token, 0xF01FF, IntPtr.Zero, 2, 2, out token)) throw new Win32Exception();
            if (restricted)
            {
                SecurityIdentifier admins = new SecurityIdentifier(WellKnownSidType.BuiltinAdministratorsSid, null);
                byte[] bytes = new byte[admins.BinaryLength];
                admins.GetBinaryForm(bytes, 0);
                GCHandle pinned = GCHandle.Alloc(bytes, GCHandleType.Pinned);
                try
                {
                    SID_AND_ATTRIBUTES[] disable = new SID_AND_ATTRIBUTES[] { new SID_AND_ATTRIBUTES { Sid = pinned.AddrOfPinnedObject() } };
                    IntPtr limited;
                    if (!CreateRestrictedToken(token, 1, 1, disable, 0, IntPtr.Zero, 0, IntPtr.Zero, out limited)) throw new Win32Exception();
                    CloseHandle(token);
                    token = limited;
                }
                finally { pinned.Free(); }
            }
            if (takeOwnership)
            {
                LUID luid;
                if (!LookupPrivilegeValue(null, "SeTakeOwnershipPrivilege", out luid)) throw new Win32Exception();
                TOKEN_PRIVILEGES privileges = new TOKEN_PRIVILEGES { Count = 1, Luid = luid, Attributes = 2 };
                AdjustTokenPrivileges(token, false, ref privileges, 0, IntPtr.Zero, IntPtr.Zero);
            }
            using (WindowsIdentity impersonated = new WindowsIdentity(token))
            {
                CloseHandle(token);
                WindowsIdentity.RunImpersonated(impersonated.AccessToken, () =>
                {
                    for (int p = 0; p < paths.Length; p++)
                        for (int r = 0; r < rights.Length; r++)
                            lines.Add(p + "|" + r + "|" + Open(paths[p], rights[r]).ToString("X8"));
                });
            }
        }
        return lines.ToArray();
    }
}
""");
