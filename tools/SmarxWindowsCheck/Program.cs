// Vérifie le moteur Windows de SMAR-X sur un vrai contrôleur de domaine. Écrit un script PowerShell qui, lancé en
// SYSTEM (tâche planifiée), recrée le serveur d'exemple (WindowsSamples.FileServer) sous C:\SmarxCheck avec des comptes
// du domaine préfixés smx- dans l'OU SMARX-Test, relève les ACL réelles telles qu'elles sont stockées (GetFileSecurity ;
// Get-Acl, lui, trie les ACE explicites par SID), puis ouvre chaque fichier et dossier
// avec chacun des 14 droits spéciaux (NtOpenFile) sous le jeton S4U de chaque compte, sans mot de passe ; pour une
// session non élevée, Administrators passe en « refus seulement » (CreateRestrictedToken), comme le fait l'UAC. Tout est
// supprimé à la fin. La sortie est le fichier de fidélité SMAR-X.Tests/Fidelity/windows-file-server.txt.
//
//   dotnet run --project tools/SmarxWindowsCheck > smarx-windows.ps1   (puis : tâche SYSTEM sur le contrôleur de domaine)
//   dotnet run --project tools/SmarxWindowsCheck -- --network ADDS.powershell.labo > smarx-net.ps1
//     (accès par les partages : sur un poste du domaine, dans la session d'un administrateur du domaine ; voir NetworkCheck)
